#!/usr/bin/env python3
"""Picks the game's pictures out of the Urizen 1-bit tileset (CC0, by vurmux) and packs the DINOBYTE
font (CC BY 4.0, by mby) into generated Odin: src/game/gfx.odin and src/game/font.odin (do not
hand-edit). Run: python3 -I tools/extract_gfx.py [--sheet out.png]

Urizen tiles are 12x12 with a 1px gap (tile (col,row) starts at 13*col+1, 13*row+1), one colour per
tile on black. Each picture is kept as a mask; the game paints it in a Sweetie-16 palette index.
--sheet also writes a contact sheet of the picks (4x scale) for checking them by eye."""
import os
import sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sheet = Image.open(os.path.join(ROOT, 'tools/data/urizen_onebit_tileset__v2d0.png')).convert('RGB')

# name -> (col, row). Order is the Gfx enum order in src/game/screen.odin.
PICKS = [
    ('Wall',        0, 2),    # grey cobblestone
    ('Floor',       2, 5),    # dotted floor
    ('Stairs_Down', 23, 0),   # user-confirmed in the Urizen catalogue
    ('Stairs_Up',   24, 0),   # user-confirmed in the Urizen catalogue
    ('Player',      104, 0),  # plain person
    ('Torch',       10, 31),  # from the tools row
    # Items (slice 1 step 3).
    ('Jools',        0, 46),  # a scatter of coins
    ('Dagger',      44, 6),
    ('Short_Sword', 39, 6),
    ('Club',        28, 7),
    ('Padded_Armour', 31, 11),
    ('Leather_Cap', 39, 12),
    ('Buckler',     28, 12),  # round wooden shield
    ('Boots',        1, 29),
    ('Bread',        1, 20),
    ('Pack',        69, 9),   # a rucksack shape (from the medical row; painted brown)
    ('Sack',        64, 30),  # a tied bag (the money bag; painted brown)
    ('Belt',         0, 29),
    ('Purse',        1, 23),  # leather pouch
    # Tenants and trophies (slice 1 step 4).
    ('Rat',          3, 14),
    ('Bat',          8, 14),
    ('Beetle',       0, 15),
    ('Spider',       2, 15),
    ('Kobold',     114, 40),  # big-eared imp
    ('Slime',      105, 42),
    ('Carny',      111, 43),  # a figure in a hat, for the sideshow barker
    ('Rat_Tail',     2, 25),  # a thin curve (from the blood row; painted pale)
    ('Bat_Wing',     5, 23),  # a feather shape
    ('Spider_Leg',   0, 25),
    ('Beetle_Shell', 5, 18),  # a round shell (from the food rows)
    ('Kobold_Ear',  14, 18),  # an ear-like curl (from the food rows)
    # Food, potions, scrolls and jewellery (slice 1 step 6).
    ('Cheese',       7, 17),  # a wedge
    ('Jerky',       19, 18),  # dried strips
    ('Potion',      30, 4),   # a round flask, painted in the potion's colour
    ('Scroll',      26, 14),
    ('Ring',        11, 43),
    ('Amulet',       2, 44),
    ('Spellbook',   30, 15),  # a tome with a symbol
    # The town (slice 1 step 7).
    ('Brick',        0, 3),
    ('Door',         4, 1),
    ('Herald',     117, 0),  # a figure holding up a notice
    # Floor 4 (slice 1 step 8).
    ('Skeleton',   104, 10),
    ('Skull',        1, 38),
    ('Bone_Pile',    4, 38),
    ('Key',          6, 45),
]

def tile(col, row):
    t = sheet.crop((13 * col + 1, 13 * row + 1, 13 * col + 13, 13 * row + 13))
    return [1 if max(t.getpixel((x, y))) > 0 else 0 for y in range(12) for x in range(12)]

out = ["// Generated by tools/extract_gfx.py from tools/data/urizen_onebit_tileset__v2d0.png. Do not hand-edit.",
       "// Urizen 1-bit tileset by vurmux, https://vurmux.itch.io/urizen-onebit-tileset, CC0 1.0.",
       "package game", "", f"GFX_COUNT :: {len(PICKS)}", "",
       "// One 12x12 mask per picture, one bit per pixel: bit (y*12 + x) of the three u64s, 48 bits each.",
       f"GFX := [{len(PICKS)}][3]u64{{"]
masks = []
for name, c, r in PICKS:
    px = tile(c, r)
    assert any(px), name
    masks.append(px)
    words = []
    for w in range(3):
        bits = 0
        for i in range(48):
            if px[w * 48 + i]:
                bits |= 1 << i
        words.append(f"0x{bits:012X}")
    out.append(f"\t{{{', '.join(words)}}}, // {name} ({c}, {r})")
out.append("}\n")
open(os.path.join(ROOT, 'src/game/gfx.odin'), 'w').write("\n".join(out))

font = Image.open(os.path.join(ROOT, 'tools/data/dbyte_1x.png')).convert('RGBA')
assert font.size == (96, 128), font.size
glyphs = []
for code in range(256):
    cx, cy = (code % 16) * 6, (code // 16) * 8
    bits = 0
    for y in range(8):
        for x in range(6):
            if font.getpixel((cx + x, cy + y))[3] > 0:
                bits |= 1 << (y * 6 + x)
    glyphs.append(bits)
lines = ["// Generated by tools/extract_gfx.py from tools/data/dbyte_1x.png (unmodified). Do not hand-edit.",
         "// DINOBYTE bitmap font by mby, https://mby.itch.io/dinobyte, CC BY 4.0.",
         "package game", "", "// 6x8 glyphs, one u64 per code page 437 character; bit (row*6 + col) is lit.",
         "FONT := [256]u64{"]
for i in range(0, 256, 4):
    lines.append("\t" + ", ".join(f"0x{g:012X}" for g in glyphs[i:i + 4]) + ",")
lines.append("}\n")
open(os.path.join(ROOT, 'src/game/font.odin'), 'w').write("\n".join(lines))

if len(sys.argv) == 3 and sys.argv[1] == '--sheet':
    img = Image.new('RGB', (len(PICKS) * 14, 14), (51, 60, 87))
    for i, px in enumerate(masks):
        for p, v in enumerate(px):
            if v:
                img.putpixel((i * 14 + 1 + p % 12, 1 + p // 12), (244, 244, 244))
    img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(sys.argv[2])

print(f"{len(PICKS)} pictures, 256 glyphs")
